export type TranslationKey = keyof typeof en;
let activeLanguage: AppLanguage = "en";

export function setLanguage(language: AppLanguage): void { activeLanguage = language; }
export function getLanguage(): AppLanguage { return activeLanguage; }
export function locale(): string { return activeLanguage === "de" ? "de-DE" : "en-US"; }
export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = (activeLanguage === "de" ? de : en)[key];
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}
